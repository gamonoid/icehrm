    /**
     * An extention of get method for the use of data tables with ability to search
     *
     * @method getData
     * @param  $table {String} model class name of the table to retive data
     * (e.g for Users table model class name is User)
     * @param  mappingStr {String} a JSON string to specify fields of the            $table                  should
     *                                                                                                       be
     *                                                                                                       mapped
     *                                                                                                       to
     *                                                                                                       other
     *                                                                                                       tables
     *                                                                                                       (e.g
     *                                                                                                       {"profile":["Profile","id","first_name+last_name"]}
     *                                                                                                       : this
     *                                                                                                       is how
     *                                                                                                       the
     *                                                                                                       profile
     *                                                                                                       field
     *                                                                                                       in
     *                                                                                                       Users
     *                                                                                                       table
     *                                                                                                       is
     *                                                                                                       mapped
     *                                                                                                       to
     *                                                                                                       Profile
     *                                                                                                       table.
     *                                                                                                       In
     *                                                                                                       this
     *                                                                                                       case
     *                                                                                                       users
     *                                                                                                       profile
     *                                                                                                       field
     *                                                                                                       will
     *                                                                                                       get
     *                                                                                                       filled
     *                                                                                                       by
     *                                                                                                       Profile
     *                                                                                                       first
     *                                                                                                       name
     *                                                                                                       and
     *                                                                                                       last
     *                                                                                                       name.
     *                                                                                                       The
     *                                                                                                       original
     *                                                                                                       value
     *                                                                                                       in
     *                                                                                                       User->profile
     *                                                                                                       field
     *                                                                                                       will
     *                                                                                                       get
     *                                                                                                       moved
     *                                                                                                       to
     *                                                                                                       User->profile_id)
     * @param  $filterStr {String} a JSON string to specify the ordering of the items
     * (e.g {"job_title":"2","department":"2"}  - this will select only items having
     * job_title = 2 and department = 2)
     * @param  $orderBy {String} a string to specify the ordering (e.g in_time desc)
     * @param  string                                                                $limit                  {String} a string to specify the limit (e.g limit 2)
     * @param  string                                                                $searchColumns          {String} a JSON string to specify names of searchable
     *                                                                                                       fields (e.g
     *                                                                                                       ["id","employee_id","first_name","last_name","mobile_phone","department","gender","supervisor"])
     * @param  string                                                                $searchTerm             {String} a string to specify term to search
     * @param  string                                                                $isSubOrdinates         {Boolean} a Boolean to specify if we only need to retive
     *                                                                                                       subordinates. Any item is a subordinate item if the item
     *                                                                                                       has "profile" field defined and the value of "profile"
     *                                                                                                       field is equal to id of one of the subordinates of
     *                                                                                                       currenly logged in profile id. (Any Profile is a
     *                                                                                                       subordinate of curently logged in Profile if the
     *                                                                                                       supervisor field of a Profile is set to the id of
     *                                                                                                       currently logged in Profile)
     * @param  string                                                                $skipProfileRestriction {Boolean} default if false - TODO - I'll explain this later
     * @return {Array} an array of objects of type $table
     */
    public function getData(
        $table,
        $mappingStr = null,
        $filterStr = null,
        $orderBy = null,
        $limit = null,
        $searchColumns = null,
        $searchTerm = null,
        $isSubOrdinates = false,
        $skipProfileRestriction = false,
        $sortData = array(),
        $countOnly = false
    ) {
        $map = [];
        if (!empty($mappingStr)) {
            $map = json_decode($mappingStr);
        }
        $nsTable = $this->getFullQualifiedModelClassName($table);
        /** @var BaseModel $obj */
        $obj = new $nsTable();
        $this->checkSecureAccess("get", $obj, $table, $_REQUEST);

        // The requested row scope is a REQUEST, not a decision: narrow it to what
        // this model actually permits before any branch below reads it.
        $isSubOrdinates = $this->resolveSubordinateListScope($isSubOrdinates, $obj, $table);
        $query = "";
        $queryData = array();
        if (!empty($filterStr)) {
            $filter = json_decode($filterStr);
            if (!empty($filter)) {
                LogManager::getInstance()->debug("Building filter query");
                if (method_exists($obj, 'getCustomFilterQuery')) {
                    LogManager::getInstance()->debug("Method: getCustomFilterQuery exists");
                    $response = $obj->getCustomFilterQuery($filter);
                    $query = $response[0];
                    $queryData = $response[1];
                } else {
                    LogManager::getInstance()->debug("Method: getCustomFilterQuery not found");
                    $defaultFilterResp = $this->buildDefaultFilterQuery($filter);
                    $query = $defaultFilterResp[0];
                    $queryData = $defaultFilterResp[1];
                }
            }

            LogManager::getInstance()->debug("Filter Query:".$query);
            LogManager::getInstance()->debug("Filter Query Data:".json_encode($queryData));
        }

        $searchJoinQuery = "";

        if (!empty($searchTerm) && !empty($searchColumns)) {
            $searchColumnList = json_decode($searchColumns);
            $searchColumnList = array_intersect($searchColumnList, $obj->getColumns());
            if (!empty($searchColumnList)) {
                $tempQuery = " and (";
                foreach ($searchColumnList as $col) {
                    if ($tempQuery != " and (") {
                        $tempQuery.=" or ";
                    }
                    $tempQuery.=$col." like ?";
                    $queryData[] = "%".$searchTerm."%";
                }

                if (!empty($map->employee) && 'Employee' != $table) {
                    $tempQuery.=" or emp.first_name like ? or emp.last_name like ?";
                    $queryData[] = "%".$searchTerm."%";
                    $queryData[] = "%".$searchTerm."%";

                    $searchJoinQuery = ' LEFT JOIN Employees emp ON emp.id = a.employee WHERE ';
                }

                $query.= $tempQuery.")";
            }
        }

        if (!empty($sortData) && $sortData['sorting']."" == "1" && isset($sortData['column'])
            && in_array($sortData['column'], $obj->getColumns(), true)
        ) {
            // Whitelist the sort column against the model's real columns and constrain the
            // direction to ASC/DESC. Both entry points reach this sink with client-supplied
            // values — the DataTables grid (sSortDir_0 via getSortingData) and the REST
            // endpoints (sortField -> DataQuery::setSortColumn) — so validating here closes
            // ORDER BY SQL injection for every caller. An unknown column falls through to
            // the default ordering below instead of being concatenated into the query.
            $sortOrder = (isset($sortData['order']) && strtoupper($sortData['order']) === 'DESC') ? 'DESC' : 'ASC';
            $orderBy = " ORDER BY ".$sortData['column']." ".$sortOrder;
        } else {
            if (empty($orderBy)) {
                $orderBy = "";
            } else {
                $orderBy = " ORDER BY ".$orderBy;
            }
        }

        if (empty($limit)) {
            $limit = "";
        }

        if ($obj->getFinder() !== null) {
            /**
 * @var FinderProxy $finder
*/
            $finder = $obj->getFinder();
        } else {
            /**
 * @var FinderProxy $finder
*/
            $finder = $obj;
        }

        $finder->setIsSubOrdinateQuery($isSubOrdinates);

        if (in_array($table, $this->userTables) && !$skipProfileRestriction) {
            $cemp = $this->getCurrentProfileId();
            if (!empty($cemp)) {
                if (!$isSubOrdinates) {
                    array_unshift($queryData, $cemp);
                    //$signInMappingField = SIGN_IN_ELEMENT_MAPPING_FIELD_NAME;
                    $signInMappingField = $obj->getUserOnlyMeAccessField();
                    LogManager::getInstance()->debug(
                        "Data Load Query (x1):".$signInMappingField." = ?".$query.$orderBy.$limit
                    );
                    LogManager::getInstance()->debug("Data Load Query Data (x1):".json_encode($queryData));

                    if ($countOnly) {
                        $list = $finder->getTotalCount(
                            $searchJoinQuery.
                            $signInMappingField
                            ." = ?".
                            $query.$orderBy.$limit,
                            $queryData
                        );
                    } else {
                        $list = $finder->Find(
                            $searchJoinQuery.
                            $signInMappingField
                            ." = ?".
                            $query.$orderBy.$limit,
                            $queryData
                        );
                    }
                } else {
                    $profileClass = $this->getFullQualifiedModelClassName(ucfirst(SIGN_IN_ELEMENT_MAPPING_FIELD_NAME));
                    $subordinate = new $profileClass();
                    $subordinates = $subordinate->Find("supervisor = ?", array($cemp));
                    $cempObj = new Employee();
                    $cempObj->Load("id = ?", array($cemp));

                    if ($obj->getUserOnlyMeAccessField() == 'id'
                        && SettingsManager::getInstance()->getSetting('System: Company Structure Managers Enabled') == 1
                        && CompanyStructure::isHeadOfCompanyStructure($cempObj->department, $cemp)
                    ) {
                        if (empty($subordinates)) {
                            $subordinates = array();
                        }

                        $childCompaniesIds = array();
                        if (SettingsManager::getInstance()->getSetting(
                            'System: Child Company Structure Managers Enabled'
                        ) == '1'
                        ) {
                            $childCompaniesResp = CompanyStructure::getAllChildCompanyStructures($cempObj->department);
                            $childCompanies = $childCompaniesResp->getObject();

                            foreach ($childCompanies as $cc) {
                                $childCompaniesIds[] = $cc->id;
                            }
                        } else {
                            $childCompaniesIds[] = $cempObj->department;
                        }

                        if (!empty($childCompaniesIds)) {
                            $childStructureSubordinates = $subordinate->Find(
                                "department in (" . implode(',', $childCompaniesIds) . ") and id != ?",
                                array($cemp)
                            );
                            $subordinates = array_merge($subordinates, $childStructureSubordinates);
                        }
                    }

                    $subordinatesIds = "";
                    foreach ($subordinates as $sub) {
                        if ($subordinatesIds != "") {
                            $subordinatesIds.=",";
                        }
                        $subordinatesIds.=$sub->id;
                    }

                    if ($obj->allowIndirectMapping()) {
                        $indeirectEmployees = $subordinate->Find(
                            "indirect_supervisors IS NOT NULL and indirect_supervisors <> '' and status = 'Active'",
                            array()
                        );
                        foreach ($indeirectEmployees as $ie) {
                            $indirectSupervisors = json_decode($ie->indirect_supervisors, true);
                            if (in_array($cemp, $indirectSupervisors)) {
                                if ($subordinatesIds != "") {
                                    $subordinatesIds.=",";
                                }
                                $subordinatesIds.=$ie->id;
                            }
                        }
                    }

                    $signInMappingField = $obj->getUserOnlyMeAccessField();
                    LogManager::getInstance()->debug(
                        "Data Load Query (x2):".$signInMappingField." in (".$subordinatesIds.") "
                        .$query.$orderBy.$limit
                    );
                    LogManager::getInstance()->debug("Data Load Query Data (x2):".json_encode($queryData));
                    if (!empty($subordinatesIds)) {
                        if ($countOnly) {
                            $list = $finder->getTotalCount(
                                $searchJoinQuery .
                                $signInMappingField . " in (" . $subordinatesIds . ") " . $query . $orderBy . $limit,
                                $queryData
                            );
                        } else {
                            $list = $finder->Find(
                                $searchJoinQuery .
                                $signInMappingField . " in (" . $subordinatesIds . ") " . $query . $orderBy . $limit,
                                $queryData
                            );
                        }
                    } else {
                        $list = array();
                    }
                }
            } else {
                $list = array();
            }
        } elseif ($isSubOrdinates) {
            $cemp = $this->getCurrentProfileId();
            if (!empty($cemp)) {
                $profileClass = $this->getFullQualifiedModelClassName(ucfirst(SIGN_IN_ELEMENT_MAPPING_FIELD_NAME));
                $subordinate = new $profileClass();
                $subordinates = $subordinate->Find("supervisor = ?", array($cemp));
                $cempObj = new Employee();
                $cempObj->Load("id = ?", array($cemp));
                if ($obj->getUserOnlyMeAccessField() == 'id'
                    && SettingsManager::getInstance()->getSetting('System: Company Structure Managers Enabled') == 1
                    && CompanyStructure::isHeadOfCompanyStructure($cempObj->department, $cemp)
                ) {
                    if (empty($subordinates)) {
                        $subordinates = array();
                    }

                    $childCompaniesIds = array();
                    if (SettingsManager::getInstance()->getSetting(
                        'System: Child Company Structure Managers Enabled'
                    ) == '1'
                    ) {
                        $childCompaniesResp = CompanyStructure::getAllChildCompanyStructures($cempObj->department);
                        $childCompanies = $childCompaniesResp->getObject();

                        foreach ($childCompanies as $cc) {
                            $childCompaniesIds[] = $cc->id;
                        }
                    } else {
                        $childCompaniesIds[] = $cempObj->department;
                    }

                    if (!empty($childCompaniesIds)) {
                        $childStructureSubordinates = $subordinate->Find(
                            "department in (" . implode(',', $childCompaniesIds) . ") and id != ?",
                            array($cemp)
                        );
                        $subordinates = array_merge($subordinates, $childStructureSubordinates);
                    }
                }

                $subordinatesIds = "";
                foreach ($subordinates as $sub) {
                    if ($subordinatesIds != "") {
                        $subordinatesIds.=",";
                    }
                    $subordinatesIds.=$sub->id;
                }

                if ($obj->allowIndirectMapping()) {
                    $indeirectEmployees = $subordinate->Find(
                        "indirect_supervisors IS NOT NULL and indirect_supervisors <> '' and status = 'Active'",
                        array()
                    );
                    foreach ($indeirectEmployees as $ie) {
                        $indirectSupervisors = json_decode($ie->indirect_supervisors, true);
                        if (in_array($cemp, $indirectSupervisors)) {
                            if ($subordinatesIds != "") {
                                $subordinatesIds.=",";
                            }
                            $subordinatesIds.=$ie->id;
                        }
                    }
                }

                $signInMappingField = $obj->getUserOnlyMeAccessField();
                LogManager::getInstance()->debug(
                    "Data Load Query (a1):".$signInMappingField." in (".$subordinatesIds.") ".$query.$orderBy.$limit
                );

				if ('id' === $signInMappingField && empty($subordinatesIds)) {
					// Getting employees for a manager
					// If there are no direct reports, return nothing.
					$list = $countOnly ? 0 : [];
				} else if (!empty($subordinatesIds)) {
                    if ($countOnly) {
                        $list = $finder->getTotalCount(
                            $searchJoinQuery.
                            $signInMappingField." in (".$subordinatesIds.") ".$query.$orderBy.$limit,
                            $queryData
                        );
                    } else {
                        $list = $finder->Find(
                            $searchJoinQuery.
                            $signInMappingField." in (".$subordinatesIds.") ".$query.$orderBy.$limit,
                            $queryData
                        );
                    }

                } else {
                    if ($countOnly) {
                        $list = 0;
                    } else {
                        $list = [];
                    }

                }
            } else {
                if ($countOnly) {
                    $list = $finder->getTotalCount($searchJoinQuery.$query.$orderBy.$limit, $queryData);
                } else {
                    $list = $finder->Find($searchJoinQuery.$query.$orderBy.$limit, $queryData);
                }

            }
        } else {
            // Not row-scoped by $userTables (empty under an admin module path) and not a
            // subordinate query. Restrict a Manager to their own team; Admin and
            // all-employee-data roles are unaffected. See managerListScopeClause().
            list($mgrClause, $mgrData) = $this->managerListScopeClause($obj);
            $mgrQueryData = array_merge($mgrData, $queryData);

            // No "1=1" anchor: the clause already begins with " and ", and
            // BaseModel::refineWhereClause() strips a leading "and" (and collapses
            // "WHERE and" -> "where"), so it is valid on its own.
            //
            // This matters because models may override Find() and CONCATENATE this
            // string onto a clause of their own — TasksUser\Common\Model\MyTaskList does
            // Find('employee = ?' . $whereOrderBy). An anchor here produced
            // "employee = ?1=1 ORDER BY …", a SQL syntax error that stopped the tasks
            // module opening for every role. Appending " and …" composes correctly both
            // for a bare clause and for one a model has already started.
            $whereClause = $searchJoinQuery.$mgrClause.$query.$orderBy.$limit;

            if ($countOnly) {
                $list = $finder->getTotalCount($whereClause, $mgrQueryData);
            } else {
                $list = $finder->Find($whereClause, $mgrQueryData);
            }
        }

        if ($obj->ErrorMsg()) {
            LogManager::getInstance()->debug("Get Data Error:".$obj->ErrorMsg());
        }

        if ($countOnly) {
            return is_array($list)?0:(int)$list;
        }

        LogManager::getInstance()->debug("Data Load Query:".$query.$orderBy.$limit);
        LogManager::getInstance()->debug("Data Load Query Data:".json_encode($queryData));

        $processedList = array();
        foreach ($list as $obj) {
            $processedObj = $this->cleanUpAdoDB($obj->postProcessGetData($obj));
            if (null !== $processedObj) {
                $processedList[] = $processedObj;
            }
        }

        $list = $processedList;

        if (!empty($mappingStr) && is_object($map)) {
            $list = $this->populateMapping($list, $map);
        }

        return $list;
    }

    /**
     * Propulate field mappings for a given set of objects
     *
     * @method populateMapping
     * @param  $list {Array} array of model objects
     * @param  $map {Array} an associative array of Mappings (e.g {"profile":["Profile","id","first_name+last_name"]})
     * @return {Array} array of populated objects
     */

    public function populateMapping($list, $map)
    {
        $listNew = array();
        if (empty($list)) {
            return $listNew;
        }
        foreach ($list as $item) {
            $item = $this->populateMappingItem($item, $map);
            $listNew[] = $item;
        }
        return  $listNew;
    }

    /**
     * Whether a client-supplied source-mapping triple [Model, lookupCol, displayCols]
     * may be resolved. The lookup and display columns arrive verbatim in the `sm`
     * request parameter, which is never sanitised — so without this both are an
     * attack surface:
     *
     *   - lookupCol ($v[1]) is concatenated into the WHERE string, so a value like
     *     "1=1 OR (subquery)" is SQL injection;
     *   - displayCol ($v[2]) is read straight off the target row, so "password" on a
     *     User mapping returns bcrypt hashes, bypassing the target model's own ACL.
     *
     * A mapping is server-side picker resolution, so the same allowlist the pickers
     * use applies: every column must be a published fieldValueFields() entry of the
     * target model. That is a real column (kills the injection) AND one the model has
     * declared safe to expose (kills the password/PII read). Deny by default — a
     * model that publishes nothing cannot be a mapping target at all.
     */
    private function mappingFieldsAllowed($targetObj, $v)
    {
        if (!is_array($v) || count($v) < 3) {
            return false;
        }
        $allowed = method_exists($targetObj, 'fieldValueFields')
            ? (array) $targetObj->fieldValueFields()
            : array();
        if (empty($allowed)) {
            return false;
        }
        // Split display columns on '+' OR space: populateMappingItem() normalises the
        // two the same way (str_replace('+',' ') then explode(' ')), and a '+' can
        // reach us decoded to a space when a caller sends the mapping unencoded. Parse
        // both here so the allowlist agrees with how the value is actually resolved.
        $requested = array_merge(array($v[1]), preg_split('/[+ ]+/', (string) $v[2]));
        foreach ($requested as $col) {
            $col = trim($col);
            if ($col === '' || !in_array($col, $allowed, true)) {
                LogManager::getInstance()->info(sprintf(
                    'MAPPING_FIELD_DENIED: %s.%s is not a published picker field',
                    isset($v[0]) ? $v[0] : '?',
                    $col
                ));
                return false;
            }
        }
        return true;
    }

    public function populateMappingItem($item, $map)
    {
        foreach ($map as $k => $v) {
            if (!isset($item->$k)) {
                continue;
            }

            $fTable = $this->getFullQualifiedModelClassName($v[0]);
            $tObj = new $fTable();
            if (!$this->mappingFieldsAllowed($tObj, $v)) {
                continue;
            }
            $tObj = $tObj->Find($v[1]."= ?", array($item->$k));

            if (is_array($tObj) && !empty($tObj)) {
                $tObj = $tObj[0];
            } else {
                continue;
            }

            if ($tObj->{$v[1]} == $item->$k) {
                $v[2] = str_replace("+", " ", $v[2]);
                $values = explode(" ", $v[2]);
                if (count($values) == 1) {
                    $idField = $k."_id";
                    $item->$idField = $item->$k;
                    $item->$k = $tObj->{$v[2]};
                } else {
                    $objVal = "";
                    foreach ($values as $val2) {
                        if ($objVal != "") {
                            $objVal .= " ";
                        }
                        $objVal .= $tObj->$val2;
                    }
                    $idField = $k."_id";
                    $item->$idField = $item->$k;
                    $item->$k = $objVal;
                }
            }
        }
        return  $item;
    }

    /**
     * Retive one element from db
     *
     * @method getElement
     * @param  $table {String} model class name of the table to get data (e.g for Users table model class name is User)
     * @param  table {Integer} id of the item to get from                                                 $table
     * @param  mappingStr {String} a JSON string to specify fields of the                                 $table should be mapped to other
     *                                                                                                          tables (e.g
     *                                                                                                          {"profile":["Profile","id","first_name+last_name"]}
     *                                                                                                          : this is how the profile
     *                                                                                                          field in Users table is
     *                                                                                                          mapped to Profile table.
     *                                                                                                          In this case users profile
     *                                                                                                          field will get filled by
     *                                                                                                          Profile first name and
     *                                                                                                          last name. The original
     *                                                                                                          value in User->profile
     *                                                                                                          field will get moved to
     *                                                                                                          User->profile_id)
     * @param  $skipSecurityCheck {Boolean} if true won't check whether the user has access to that object
     * @return {Object} an object of type $table
     */

    public function getElement($table, $id, $mappingStr = null, $skipSecurityCheck = false)
    {
        $nsTable = $this->getFullQualifiedModelClassName($table);
        $obj = new $nsTable();

        if (in_array($table, $this->userTables)) {
            $cemp = $this->getCurrentProfileId();
            if (!empty($cemp)) {
                $obj->Load("id = ?", array($id));
            } else {
            }
        } else {
            $obj->Load("id = ?", array($id));
        }

        if (!$skipSecurityCheck) {
            $this->checkSecureAccess("element", $obj, $table, $_POST);
        }

        if ($obj->id == $id) {
            if (!empty($mappingStr)) {
                $map = json_decode($mappingStr);
                $obj = $this->enrichObjectMappings($map, $obj);
            }

            //Add custom fields
            $obj = $this->enrichObjectCustomFields($table, $obj);

            $obj = $obj->postProcessGetElement($obj);
            $obj = $this->cleanUpAdoDB($obj);

            // Withhold columns this viewer may not see (finding 2.7). Only for calls that
            // went through the security check — $skipSecurityCheck marks trusted internal
            // loads (session profile bootstrap, attendance managers, job enrichment...),
            // which need the whole record and are not a user-facing disclosure boundary.
            if (!$skipSecurityCheck) {
                $obj = $this->projectForViewer($obj);
            }

            return $obj;
        }
        return null;
    }

    /**
     * @param $nameField
     * @param $targetObject
     * @return string
     */
    private function getCombinedValue($nameField, $targetObject)
    {
        $values = explode("+", $nameField);
        if (count($values) == 1) {
            return $targetObject->{$nameField};
        }
        $objVal = '';
        foreach ($values as $value) {
            if ($objVal != "") {
                $objVal .= " ";
            }
            if (substr($value, 0, 1) !== ':') {
                $objVal .= $targetObject->{$value};
            } else {
                $objVal .= substr($value, 1);
            }
        }

        return $objVal;
    }

    /**
     * Add an element to a given table
     *
     * @method addElement
     * @param  $table {String} model class name of the table to add data (e.g for Users table model class name is User)
     * @param  $obj {Array} an associative array with field names and values for the new object.
     * If the object id is not empty an existing object will be updated
     * @param  null                                                                            $postObject
     * @return IceResponse {Object} newly added or updated element of type $table newly added or updated
     * element of type $table
     */

    public function addElement($table, $obj, $postObject = null)
    {

        $customFields = array();
        $isAdd = true;
        $nsTable = $this->getFullQualifiedModelClassName($table);
        $ele = new $nsTable();


        if ($ele->validateCSRF()
            && (empty($obj->csrf) || $obj->csrf !== SessionUtils::getSessionObject('csrf-'.$table))
        ) {
            return new IceResponse(
                IceResponse::ERROR,
                "CSRF Error"
            );
        }

        if (!empty($obj['id'])) {
            $ele->Load('id = ?', array($obj['id']));
            // A request id that matches NO row is an insert, not an update — decide from
            // what actually loaded, never from the request. Keying this off $obj['id']
            // let a caller pass a non-existent id to get the worst of both: authorised as
            // "save" rather than "add", skipped by the owner-forcing block below (which
            // tested the request id), and skipped by the re-parenting guard (which needs a
            // persisted row) — so Save() inserted a NEW row owned by whatever employee the
            // request named. Live-verified: an employee created an Attendance row owned by
            // a colleague via a=add&t=Attendance&id=999999999&employee=<victim>.
            $isAdd = empty($ele->id);
        }

        // Remember the PERSISTED owner before the request is copied over the object, so an
        // update cannot re-parent the row onto somebody else. The owner is only forced on
        // INSERT below (empty id); on UPDATE it used to be taken straight from the request,
        // while userOwnsUserScopedRecord() re-reads the persisted owner and therefore still
        // saw the caller as the owner — so an employee could POST
        // a=add&t=Attendance&id=<own row>&employee=<victim> and move a fabricated record
        // onto a colleague. Restored after the copy loop for non-Admin callers.
        $ownerFieldName = $ele->getUserOnlyMeAccessField();
        $persistedOwner = null;
        if (!$isAdd && !empty($ownerFieldName) && $ownerFieldName !== 'id' && !empty($ele->id)) {
            $persistedOwner = $ele->$ownerFieldName;
        }

        $objectKeys = $ele->getObjectKeys();

        // Mass-assignment guard: fields the current actor may not set on this record are
        // dropped from the request copy, so the loaded DB value (update) or model default
        // (add) is kept. $ele is already loaded here, so getProtectedFields() sees the
        // record's real id/owner. Default is empty — no behaviour change for other models.
        $protectedFields = $ele->getProtectedFields($this->getCurrentUser());

        foreach ($obj as $k => $v) {
            if ($k == 'id' || $k == 't' || $k == 'a') {
                continue;
            }
            if (!empty($protectedFields) && in_array($k, $protectedFields, true)) {
                continue;
            }
            if ($v == "NULL") {
                $v = null;
            }
            if (isset($objectKeys[$k])) {
                $ele->$k = $v;
            }
        }

        // Re-parenting guard (see $persistedOwner above): a non-Admin may not change which
        // employee an existing record belongs to. Admin levels and roles granted all
        // employee data still can, so HR corrections keep working.
        if ($persistedOwner !== null
            && (string) $ele->$ownerFieldName !== (string) $persistedOwner
        ) {
            $actor = $this->getCurrentUser();
            $actorIsAdmin = !empty($actor)
                && in_array($actor->user_level, array('Admin', 'Restricted Admin'), true);
            if (!$actorIsAdmin && !\Employees\Common\Model\EmployeeAccess::hasAccessToAllEmployeeData()) {
                $ele->$ownerFieldName = $persistedOwner;
            }
        }

        // $isAdd, not empty($obj['id']): an id that matched no row is an insert and must
        // still have its owner forced to the caller (see the Load above).
        if ($isAdd) {
            if (in_array($table, $this->userTables)) {
                $cemp = $this->getCurrentProfileId();
                if (!empty($cemp)) {
                    $signInMappingField = SIGN_IN_ELEMENT_MAPPING_FIELD_NAME;
                    $ele->$signInMappingField = $cemp;
                } else {
                    return new IceResponse(IceResponse::ERROR, "Profile id is not set");
                }
            }
        }

        if ($postObject === null) {
            $this->checkSecureAccess($isAdd?"add":"save", $ele, $table, $_POST);
        } else {
            $this->checkSecureAccess($isAdd?"add":"save", $ele, $table, $postObject);
        }


        $resp = $ele->validateSave($ele);
        if ($resp->getStatus() != IceResponse::SUCCESS) {
            return $resp;
        }

        if ($isAdd) {
            if (empty($ele->created)) {
                $ele->created = date("Y-m-d H:i:s");
            }
        }

        if (empty($ele->updated)) {
            $ele->updated = date("Y-m-d H:i:s");
        }
        if ($isAdd) {
            $preResponse = $ele->executePreSaveActions($ele);
        } else {
            $preResponse = $ele->executePreUpdateActions($ele);
        }

        if ($preResponse->getStatus() === IceResponse::ERROR) {
            return $preResponse;
        }

        $ele = $preResponse->getData();

        $ok = $ele->Save();

        if (!$ok) {
            $error = $ele->ErrorMsg();

            LogManager::getInstance()->info($error);

            if ($isAdd) {
                $this->audit(
                    IceConstants::AUDIT_ERROR,
                    "Error occurred while adding an object to ".$table." \ Error: ".$error
                );
            } else {
                $this->audit(
                    IceConstants::AUDIT_ERROR,
                    "Error occurred while editing an object in ".$table." [id:".$ele->id."] \ Error: ".$error
                );
            }
            return new IceResponse(IceResponse::ERROR, $this->findError($error));
        }

        $customFields = $ele->getCustomFields($obj);
        foreach ($obj as $k => $v) {
            if (isset($customFields[$k])) {
                $this->customFieldManager->addCustomField($ele->getCustomFieldTable($table), $ele->id, $k, $v);
            }
        }

        if ($isAdd) {
            $ele->executePostSaveActions($ele);
            $this->audit(IceConstants::AUDIT_ADD, "Added an object to ".$table." [id:".$ele->id."]");
        } else {
            $ele->executePostUpdateActions($ele);
            $this->audit(IceConstants::AUDIT_EDIT, "Edited an object in ".$table." [id:".$ele->id."]");
        }

        return new IceResponse(IceResponse::SUCCESS, $ele);
    }

    /**
     * Delete an element if not the $table and $id is defined as a non deletable
     *
     * @method deleteElement
     * @param  $table {String} model class name of the table to delete data
     * (e.g for Users table model class name is User)
     * @param  $id {Integer} id of the item to delete
     * @return NULL
     */
    public function deleteElement($table, $id)
    {
        $fileFields = $this->fileFields;
        $nsTable = $this->getFullQualifiedModelClassName($table);
        /**
 * @var BaseModel $ele
*/
        $ele = new $nsTable();

        $ele->Load('id = ?', array($id));

        if (empty($ele->id) || $ele->id !== intval($id)) {
            return new IceResponse(
                IceResponse::ERROR,
                "Item not found"
            );
        }

        $preDeleteResponse = $ele->executePreDeleteActions($ele);
        if ($preDeleteResponse->getStatus() !== IceResponse::SUCCESS) {
            return $preDeleteResponse;
        }

        $this->checkSecureAccess("delete", $ele, $table, $_POST);

        if (isset($this->nonDeletables[$table])) {
            $nonDeletableTable = $this->nonDeletables[$table];
            if (!empty($nonDeletableTable)) {
                foreach ($nonDeletableTable as $field => $value) {
                    if ($ele->$field == $value) {
                        return new IceResponse(
                            IceResponse::ERROR,
                            "This item can not be deleted"
                        );
                    }
                }
            }
        }
        //Delete approval requests
        if (class_exists("\\Employees\\Common\\ModelEmployeeApproval")) {
            $approvalRequest = new EmployeeApproval();
            $approvalRequests = $approvalRequest->Find("type = ? and element = ?", array($table, $id));
            foreach ($approvalRequests as $approvalRequest) {
                $approvalRequest->Delete();
            }
        }

        $ok = $ele->Delete();
        if (!$ok) {
            $error = $ele->ErrorMsg();
            LogManager::getInstance()->info($error);
            return new IceResponse(
                IceResponse::ERROR,
                $this->findError($error)
            );
        } else {
            //Backup
            if ($table == ucfirst(SIGN_IN_ELEMENT_MAPPING_FIELD_NAME)) {
                $newObj = $this->cleanUpAdoDB($ele);
                $dataEntryBackup = new DataEntryBackup();
                $dataEntryBackup->tableType = $table;
                $dataEntryBackup->data = json_encode($newObj);
                $dataEntryBackup->Save();
            }
            $ele->executePostDeleteActions($ele);
            $this->audit(IceConstants::AUDIT_DELETE, "Deleted an object in ".$table." [id:".$ele->id."]");
        }

        if (isset($fileFields[$table])) {
            foreach ($fileFields[$table] as $k => $v) {
                if (!empty($ele->$k)) {
                    FileService::getInstance()->deleteFileByField($ele->$k, $v);
                }
            }
        }

        $cfs = $this->customFieldManager->getCustomFields($table, $id);
        /**
 * @var CustomField $cf
*/
        foreach ($cfs as $cf) {
            $cf->Delete();
        }

        return new IceResponse(
            IceResponse::SUCCESS,
            null
        );
    }

    /**
     * Get associative array of by retriving data from $table using $key field ans key and
     * $value field as value. Mainly used for getting data for populating option lists of select
     * boxes when adding and editing items
     *
     * @method getFieldValues
     * @param  $table {String} model class name of the table to get data (e.g for Users table model class name is User)
     * @param  $key {String} key field name
     * @param  $value {String} value field name (multiple fileds cam be concatinated using +) - e.g first_name+last_name
     * @param  $method {String} if not empty, use this menthod to get only a selected set of objects
     * from db instead of retriving all objects. This method should be defined in class $table
     * and should return an array of objects of type $table
     * @return {Array} associative array
     */

    public function getFieldValues($table, $key, $value, $method, $methodParams = null)
    {

        $values = explode("+", $value);

        $ret = array();
        $nsTable = $this->getFullQualifiedModelClassName($table);
        $ele = new $nsTable();

        $finder = $ele->getFieldMappingFinder();
        if ($finder !== null) {
            $ele = $finder;
        }

        $this->checkSecureAccess("get", $ele, $table, $_POST);

        // $key and $value name COLUMNS and arrive straight from the request —
        // service.php sanitises t/ft/ob/sSearch/cl but not these. Unchecked, any
        // caller holding "get" on this model could project any column of every row
        // (Find('1 = 1') below ignores the row scoping in get()/getData()), which is
        // how a plain employee could read every colleague's address and phone
        // number. The model publishes what its pickers may ask for; anything else
        // fails closed so a missed opt-in shows up as an empty dropdown, not a leak.
        $allowedFields = array();
        if (method_exists($ele, 'fieldValueFields')) {
            $allowedFields = (array) $ele->fieldValueFields();
        }
        $requestedFields = array_merge(array($key), explode('+', (string) $value));
        foreach ($requestedFields as $requestedField) {
            $requestedField = trim($requestedField);
            if ($requestedField === '' || !in_array($requestedField, $allowedFields, true)) {
                LogManager::getInstance()->info(sprintf(
                    'FIELD_VALUES_DENIED: %s is not a published picker field on %s (allowed: %s)',
                    $requestedField,
                    $table,
                    $allowedFields ? implode(',', $allowedFields) : 'none'
                ));
                return array();
            }
        }

        if (!empty($method)) {
            if (method_exists($ele, $method) && in_array($method, $ele->fieldValueMethods())) {
                if (!empty($methodParams)) {
                    $list = $ele->$method(json_decode($methodParams));
                } else {
                    $list = $ele->$method(array());
                }
            } else {
                LogManager::getInstance()->error("Could not find method:".$method." in Class:".$table);
                $list = $ele->Find('1 = 1', array());
            }
        } else {
            $list = $ele->Find('1 = 1', array());
        }

        foreach ($list as $obj) {
            $obj = $this->cleanUpAdoDB($obj);
            if (count($values) == 1) {
                $ret[(string)$obj->$key] = $obj->$value;
            } else {
                $objVal = "";
                foreach ($values as $v) {
                    if ($objVal != "") {
                        $objVal .= " ";
                    }
                    $objVal .= $obj->$v;
                }
                $ret[(string)$obj->$key] = $objVal;
            }
        }
        return $ret;
    }

