    /**
     * HMAC used to sign the unauthenticated file-download URLs (service.php?a=download,
     * which deliberately bypasses the login gate when a signature is present).
     *
     * This used to key on the 'Instance: Key' setting. That row is written only when an
     * admin pastes a verification key into the Connect dialog, and the installer seeds
     * no such row — so on the great majority of installs getSetting() returned null and
     * this degenerated to an HMAC under an empty key, i.e. a signature anyone could
     * compute offline for any file name. APP_SEC is a 256-bit CSPRNG secret peppered
     * with the config-file APP_PASSWORD and is always defined by server.includes.inc.php.
     */
    /**
     * Whether outbound HTTPS calls should verify the peer certificate.
     *
     * True everywhere except the development environment. These requests carry the
     * instance access token and, in the marketplace's case, deliver code that is
     * extracted into the application tree — so an unverified connection is a
     * remote-code-execution channel, not a nicety.
     *
     * The one exception is development, which talks to the staging licence/marketplace
     * server (APP_WEB_URL = dascore.org) whose certificate does not validate. ICEHRM_ENV
     * defaults to 'production' in config.base.php, so anything that has not explicitly
     * declared itself development — including every customer install — verifies.
     *
     * @return bool
     */
    public static function shouldVerifyOutboundTls()
    {
        return !(defined('ICEHRM_ENV') && ICEHRM_ENV === 'development');
    }

    /**
     * The application secret (APP_SEC). Recomputed with the identical derivation when
     * the constant is not yet defined — e.g. a CLI/cron entry point that has not run
     * server.includes.inc.php — so a value encrypted in one context still decrypts in
     * another.
     */
    public function getAppSecret() {
        if (defined('APP_SEC')) {
            return APP_SEC;
        }
        $pepper = defined('APP_PASSWORD') ? APP_PASSWORD : '';

        return hash_hmac('sha256', $this->getSigningSecret(), $pepper);
    }

    public function createHash($data) {
        return hash_hmac("sha256", $data, $this->getAppSecret());
    }

    public function verifyHash($data, $hash) {
        // hash_equals: constant-time, and refuses the non-string values a crafted
        // request can otherwise pass in (e.g. signature[]=...).
        if (!is_string($hash)) {
            return false;
        }
        return hash_equals($this->createHash($data), $hash);
    }

    public function getSystemData($name)
    {
        $sysData = new SystemData();
        $sysData->Load('name = ?', [$name]);
        if (!empty($sysData->id) && $sysData->name === $name) {
            $value = $sysData->value;
            if ($value === null) {
                return null;
            }

            // Try to unserialize, return raw value if it fails.
            // allowed_classes => false: every consumer of SystemData reads plain
            // arrays/scalars, and the write path (ConnectionService::saveConnectionData)
            // stores a decoded remote response — so object instantiation here would be a
            // deserialization gadget sink with no legitimate use.
            $unserialized = @unserialize($value, array('allowed_classes' => false));
            if ($unserialized === false && $value !== serialize(false)) {
                return $value;
            }

            return $unserialized;
        }

        return null;
    }

